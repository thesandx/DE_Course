#!/usr/bin/env python3
"""Collect the built videos into the files the app reads.

    python collect.py --course gcp|de --work <dir> [--videos <dir>] [--partial]

`--work` is the folder `make_video.py` wrote to. For each script in the
course folder (`gcp/` or `de/`) this reads `<work>/<slug>/meta.json` and writes:

- `lib/course/videos/<course>.ts`: the length, chapters, captions and quick
  checks of every video. Run `pnpm format` after this script.
- `public/<course>/videos/<slug>.jpg` and `<slug>.vtt`: the poster and the captions.
- `<videos>/<slug>.mp4`, if `--videos` is given: the files to upload to the
  bucket. The MP4 files do not go into the repository.

A script that has no built video stops the collect script. With `--partial`
the collect script leaves that video out. Use it for a local preview only: the tests
want a video for every station and every track.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
COURSES = ("gcp", "de")

# A quick check opens this long before the next chapter starts, in the silence
# between two chapters.
CHECK_LEAD = 0.3

HEADER = """import type { CourseVideo } from '@/types/video';

/**
 * Written by `scripts/course-videos/collect.py`. Do not edit this file by hand.
 * Change the script in `scripts/course-videos/`, build the video
 * again, then run the collect script.
 */
export const VIDEO_TIMINGS: Readonly<Record<string, CourseVideo>> = """


def collect(scripts: Path, slug: str, work: Path) -> dict:
    script = json.loads((scripts / f"{slug}.json").read_text())
    out = work / slug
    meta_path = out / "meta.json"
    if not meta_path.exists() or not (out / f"{slug}.mp4").exists():
        sys.exit(f"{slug}: no built video in {out}")
    meta = json.loads(meta_path.read_text())
    chapters = meta["chapters"]
    titles = [chapter["title"] for chapter in script["chapters"]]
    if titles != [chapter["title"] for chapter in chapters]:
        sys.exit(f"{slug}: the built video is older than the script (chapters differ)")

    checks = []
    for index, chapter in enumerate(script["chapters"]):
        check = chapter.get("check")
        if check is None:
            continue
        if index + 1 >= len(chapters):
            sys.exit(f"{slug}: a check needs a chapter after it")
        if not 0 <= check["answer"] < len(check["options"]):
            sys.exit(f"{slug}: the answer of {chapter['title']!r} is not an option")
        checks.append(
            {
                "at": round(chapters[index + 1]["start"] - CHECK_LEAD, 2),
                "prompt": check["prompt"],
                "options": check["options"],
                "answers": [check["answer"]],
                "why": check["why"],
            }
        )

    return {
        "slug": slug,
        "duration": meta["duration"],
        "chapters": chapters,
        "cues": [{"start": start, "end": end, "text": text} for start, end, text in meta["cues"]],
        "checks": checks,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--course", required=True, choices=COURSES)
    parser.add_argument("--work", required=True, type=Path)
    parser.add_argument("--videos", type=Path)
    parser.add_argument("--partial", action="store_true")
    args = parser.parse_args()

    scripts = HERE / args.course
    timings = REPO / f"lib/course/videos/{args.course}.ts"
    public = REPO / f"public/{args.course}/videos"
    slugs = sorted(path.stem for path in scripts.glob("*.json"))
    if args.partial:
        slugs = [slug for slug in slugs if (args.work / slug / f"{slug}.mp4").exists()]
    videos = {slug: collect(scripts, slug, args.work) for slug in slugs}

    public.mkdir(parents=True, exist_ok=True)
    if args.videos:
        args.videos.mkdir(parents=True, exist_ok=True)
    for slug in slugs:
        out = args.work / slug
        shutil.copyfile(out / f"{slug}.jpg", public / f"{slug}.jpg")
        shutil.copyfile(out / "captions.vtt", public / f"{slug}.vtt")
        if args.videos:
            shutil.copyfile(out / f"{slug}.mp4", args.videos / f"{slug}.mp4")

    timings.write_text(HEADER + json.dumps(videos, ensure_ascii=False, indent=2) + ";\n")
    seconds = sum(video["duration"] for video in videos.values())
    print(f"{len(slugs)} videos, {seconds / 60:.1f} minutes, {sum(len(v['checks']) for v in videos.values())} checks")


if __name__ == "__main__":
    main()
